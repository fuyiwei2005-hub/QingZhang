import assert from "node:assert/strict";
import {fileURLToPath} from "node:url";
import { build } from "esbuild";
import { mkdirSync } from "node:fs";
mkdirSync(new URL("../.deploy/", import.meta.url), {recursive:true});
await build({entryPoints:[fileURLToPath(new URL("../lib/life.ts",import.meta.url))],bundle:true,platform:"node",format:"esm",outfile:fileURLToPath(new URL("../.deploy/life-check.mjs",import.meta.url))});
const {lifeInput,annualDate,nextBill,moneyTotal,dayDiff}=await import("../.deploy/life-check.mjs");
assert.equal(annualDate("2000-02-29","2027-02-01"),"2027-02-28");
assert.equal(annualDate("2000-02-29","2027-03-01"),"2028-02-29");
assert.equal(annualDate("2030-05-01","2026-01-01"),"2030-05-01");
assert.equal(dayDiff("2026-10-27","2026-10-26"),1);
const item={id:1,data:{kind:"subscription",date:"2026-01-31",frequency:"monthly"}};
assert.equal(nextBill(item,[]),"2026-01-31");
assert.equal(nextBill(item,[{itemId:1,date:"2026-01-31"}]),"2026-02-28");
assert.equal(nextBill(item,[{itemId:1,date:"2026-01-31"},{itemId:1,date:"2026-02-28"}]),"2026-03-31");
assert.equal(moneyTotal([{itemId:1,amount:.1},{itemId:1,amount:.2}],1),.3);
assert.equal(lifeInput.safeParse({kind:"goal",title:"A",amount:1.234,date:null}).success,false);
assert.equal(lifeInput.safeParse({kind:"anniversary",title:"A",date:"2026-02-30",yearly:true}).success,false);
assert.equal(lifeInput.safeParse({kind:"debt",title:"A",person:"B",amount:-1,date:null,direction:"lent"}).success,false);
assert.equal(lifeInput.safeParse({kind:"shopping",title:"Milk",group:"Food",amount:null,done:false}).success,true);
console.log("PASS: life validation, cents, monthly anchors, leap anniversaries and date arithmetic");
